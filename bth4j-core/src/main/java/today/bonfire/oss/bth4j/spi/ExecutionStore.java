package today.bonfire.oss.bth4j.spi;

import java.time.Duration;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;

/**
 * The transitions workers and producers make. Each method is atomic together with its checks: a
 * revision-checked transition has no effect, and reports so, when the task's revision or state differs from
 * what the caller expects. Only the worker holding the current revision of a LEASED task can move it on.
 * <p>
 * Revision rules: claim, promote, every terminal transition, reschedule, unclaim and admin changes to a
 * task that is not LEASED add one to the revision. {@link #renew}, {@link #saveStep}, {@link #progress} and
 * admin changes to a LEASED task do not, so a running worker keeps its fence.
 */
public interface ExecutionStore extends TaskStore {

    /**
     * Stores a new task in state QUEUED, or SCHEDULED when {@link TaskRecord#due()} is in the future. The
     * store sets {@code due} to its own time when it is null, and sets {@code stateChanged}.
     * <p>
     * When the record has a {@link TaskRecord#uniqueKey()} and another task holds it, nothing is stored and
     * {@link EnqueueOutcome.DuplicateKey} names that task. A key is held while its task is not terminal, and
     * after that until {@link TaskRecord#keyUntil()} when {@link TaskRecord#keyKeep()} was set.
     *
     * @return {@link EnqueueOutcome#STORED}, {@link EnqueueOutcome#EXISTS} when the id already exists in
     *         any state, or a duplicate-key outcome. The client takes EXISTS for an id generated by another
     *         writer, so a store whose transport may resend a write must answer STORED when the resend finds
     *         its own earlier write (the Redis store does this with a per-record write token).
     */
    EnqueueOutcome enqueue(TaskRecord task);

    /** {@link #enqueue} for several tasks, in order, in as few round trips as the store allows. */
    List<EnqueueOutcome> enqueueAll(List<TaskRecord> tasks);

    /**
     * Atomically moves up to {@link ClaimRequest#count()} queued tasks to LEASED across all grants.
     * In grant order, skip paused queues and zero shares, and claim up to the smaller of the share and
     * remaining count. A grant filled that first pass only when it took that positive amount in full.
     * In a second pass in the same order, only filled grants may claim more, up to their cap minus what
     * they already took and the remaining count.
     * <p>
     * Within each queue tasks are read by {@code (due, id)}; a store may order equal-due tasks by the id's
     * decimal text (the Redis store does). Tasks outside {@link ClaimRequest#knownTypeIds()} are left
     * unchanged, including their due time; null accepts every type. Each claim adds one to {@code attempts},
     * sets {@code claimedAt} and keeps {@code due}, returning the new revision, lease and worker.
     * <p>
     * A claimed task with a stored value that cannot be read is left out of the result, and its lease ends at
     * once, so that {@link MaintenanceStore#reclaim} hands it to maintenance, which ends it DEAD. The other tasks
     * of the claim are returned as usual.
     */
    List<TaskRecord> claim(ClaimRequest request);

    /**
     * Extends the lease of each task whose revision still matches, is LEASED and whose lease has not expired.
     * A lease that already ran out is reported as not owned and left alone: from then on the maintenance
     * sweeper may take the task over, and an extension must not race with that.
     *
     * @return one status per lease, in the same order
     */
    List<LeaseStatus> renew(List<LeaseRef> leases, Duration lease);

    /**
     * Completes a LEASED task: state SUCCEEDED, or the record is removed when {@code keep} is false. The
     * unique key is released or scheduled for release per {@link TaskRecord#keyKeep()}.
     *
     * @param keepPayload false drops {@link TaskRecord#encodedPayload()}; steps are kept
     * @param effect applied to a recurring definition in the same atomic step when the ack applies; may be null
     * @return false when the revision did not match
     */
    boolean ack(long id, int revision, boolean keep, boolean keepPayload, ScheduleEffect effect);

    /**
     * {@link #ack} without a schedule effect for several tasks, each checked and applied as if acknowledged on
     * its own, in as few round trips as the store allows. When the call throws, any of them may have applied.
     *
     * @return per lease whether its ack applied, in the same order
     */
    default List<Boolean> ackAll(List<LeaseRef> leases, boolean keep, boolean keepPayload) {
        var out = new ArrayList<Boolean>(leases.size());
        for (var lease : leases) out.add(ack(lease.id(), lease.revision(), keep, keepPayload, null));
        return out;
    }

    /**
     * Records a failed attempt of a LEASED task. The task is SCHEDULED for {@code retryAt}, or DEAD when
     * {@code retryAt} is null or the attempts are exhausted. The failure is appended to
     * {@link TaskRecord#failures()}, which the store bounds to the last 20. It must work for a task with stored
     * values that cannot be read, so that such a task can still end; the store may drop stored failures it
     * cannot read.
     *
     * @param keepDead false removes a dead task at once instead of keeping it for inspection
     * @param effect applied to a recurring definition in the same atomic step, only when the outcome is
     *     {@link FailOutcome#DEAD}; may be null
     */
    FailOutcome fail(
            long id, int revision, FailureInfo failure, Instant retryAt, boolean keepDead, ScheduleEffect effect);

    /**
     * Same as {@link #fail} for a task whose lease {@link MaintenanceStore#reclaim} found expired; also
     * {@link FailOutcome#LOST} when the lease is no longer expired, because its worker renewed it meanwhile.
     */
    FailOutcome failExpired(
            long id, int revision, FailureInfo failure, Instant retryAt, boolean keepDead, ScheduleEffect effect);

    /**
     * Moves a LEASED task to SCHEDULED for {@code due} and gives the attempt back.
     *
     * @return false when the revision did not match
     */
    boolean reschedule(long id, int revision, Instant due);

    /**
     * Returns a LEASED task to its queue with its due time unchanged and gives the attempt back.
     *
     * @return false when the revision did not match
     */
    boolean unclaim(long id, int revision);

    /**
     * Replaces the steps of a LEASED task. The caller passes the complete map; the store writes it as given.
     *
     * @return false when the revision did not match
     */
    boolean saveSteps(long id, int revision, java.util.Map<String, StepResult> steps);

    /**
     * Sets the progress text of a LEASED task.
     *
     * @return false when the revision did not match
     */
    boolean progress(long id, int revision, String progress);

    /**
     * Ends a LEASED task whose worker stopped it on a cancel request: state CANCELLED, {@code cancelReason}
     * set, {@code cancelRequestedAt} kept or set now, lease cleared, unique key handled like {@link #ack}.
     *
     * @param keepPayload false drops {@link TaskRecord#encodedPayload()}
     * @param effect applied to a recurring definition in the same atomic step when the task ends; may be null
     * @return false when the revision did not match
     */
    boolean finishCancelled(long id, int revision, String reason, boolean keepPayload, ScheduleEffect effect);

    /**
     * Same as {@link #finishCancelled} for a task whose lease {@link MaintenanceStore#reclaim} found expired;
     * also false when the lease is no longer expired, because its worker renewed it meanwhile.
     *
     * @param effect applied to a recurring definition in the same atomic step when the task ends; may be null
     */
    boolean finishCancelledExpired(long id, int revision, String reason, boolean keepPayload, ScheduleEffect effect);
}
